"""Generate original pixel art and memory initializers, without external assets.

Run from any directory: python tools/build_assets.py. Coordinate convention is
row-major. Sprite zero texels are transparent before palette-bank lookup.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets'
OUT.mkdir(parents=True, exist_ok=True)
BASE = [0x000000, 0x18263D, 0x285C35, 0x4F9142, 0x91BC55, 0xB59A62,
        0xE0C28A, 0x477BCA, 0x86BEEF, 0x6C526E, 0xB779A0, 0xE55C4F,
        0xF5BF4F, 0xFFF1CD, 0x97A5B6, 0xFFFFFF]
palette = []
for bank in range(16):
    for color in BASE:
        rgb = [(color >> shift) & 255 for shift in (16, 8, 0)]
        # Bank zero retains original colors; other banks are useful tints.
        if bank:
            rgb = [min(255, c * (12 + ((bank + channel * 3) % 7)) // 16)
                   for channel, c in enumerate(rgb)]
        palette.append((rgb[0] << 16) | (rgb[1] << 8) | rgb[2])

tiles = [0] * (256 * 64)
for tile in range(8):
    for y in range(8):
        for x in range(8):
            if tile == 0: c = 4 if (x * 7 + y * 3) % 19 == 0 else 3
            elif tile == 1: c = 1 if y % 4 == 0 or (x + (4 if y < 4 else 0)) % 8 == 0 else 14
            elif tile == 2: c = 6 if (x + 3 * y) % 9 else 5
            elif tile == 3: c = 8 if (x + y * 2) % 8 < 2 else 7
            elif tile == 4: c = 5 if x == 0 or y == 0 else 6
            elif tile == 5: c = 12 if x in (1, 6) or y in (1, 6) else 9
            elif tile == 6: c = 2 if (x - 3)**2 + (y - 3)**2 < 13 else 3
            else: c = 14 if (x - 3)**2 + (y - 3)**2 < 10 else 3
            tiles[tile * 64 + y * 8 + x] = c

sprites = [0] * (256 * 256)
def pixel(p, x, y, c):
    if 0 <= x < 16 and 0 <= y < 16: sprites[p * 256 + y * 16 + x] = c
def box(p, x0, y0, x1, y1, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): pixel(p, x, y, c)
# Hero: blue tunic, asymmetrical gold sword to make flipping visible.
box(0, 5, 1, 10, 3, 5); box(0, 4, 4, 11, 7, 13)
pixel(0, 6, 5, 1); pixel(0, 9, 5, 1)
box(0, 4, 8, 11, 12, 7); box(0, 4, 13, 6, 15, 1); box(0, 9, 13, 11, 15, 1)
box(0, 2, 9, 3, 12, 13); box(0, 12, 9, 13, 12, 13); box(0, 14, 5, 14, 12, 12)
# Slime and boss.
for p, fill in ((1, 4), (6, 11)):
    for y in range(3, 15):
        for x in range(1, 15):
            if (x - 7.5)**2 / 49 + (y - 10)**2 / 64 < 1: pixel(p, x, y, fill)
    box(p, 4, 8, 5, 10, 1); box(p, 10, 8, 11, 10, 1)
    box(p, 6, 12, 9, 12, 13)
    if p == 6: box(p, 2, 1, 4, 5, 12); box(p, 11, 1, 13, 5, 12)
# NPC, gem, potion, chest, heart, cursor.
box(2, 5, 1, 10, 3, 14); box(2, 4, 4, 11, 7, 6); box(2, 3, 8, 12, 14, 9)
pixel(2, 6, 5, 1); pixel(2, 9, 5, 1)
for y in range(2, 14):
    for x in range(2, 14):
        if abs(x - 7) + abs(y - 7) < 6: pixel(3, x, y, 8 if x < 7 else 7)
box(4, 6, 2, 9, 4, 5); box(4, 5, 5, 10, 6, 13); box(4, 4, 7, 11, 13, 11)
box(4, 5, 8, 5, 11, 13)
box(5, 2, 4, 13, 13, 5); box(5, 2, 7, 13, 8, 12); box(5, 7, 7, 8, 10, 12)
for y in range(2, 14):
    for x in range(1, 15):
        inside = ((x-4)**2+(y-5)**2 < 12 or (x-11)**2+(y-5)**2 < 12
                  or (y >= 5 and abs(x-7.5) < (14-y)*0.8))
        if inside: pixel(7, x, y, 11)
for y in range(2, 14):
    for x in range(2, 9 - abs(y - 7)):
        pixel(8, x, y, 15)

tilemap = [0 if 0 < x < 39 and 0 < y < 29 else 1
           for y in range(30) for x in range(40)]
for name, values, width in [('tiles', tiles, 2), ('sprites', sprites, 2),
                            ('palette', palette, 6), ('tilemap', tilemap, 2)]:
    (OUT / (name + '.hex')).write_text(''.join(f'{v:0{width}x}\n' for v in values), encoding='ascii')
with (OUT / 'gpu_assets.h').open('w', encoding='ascii') as f:
    f.write('/* Generated by tools/build_assets.py; original procedural art. */\n#pragma once\n#include <stdint.h>\n')
    for name, values, ctype in [('gpu_tiles', tiles, 'uint8_t'),
                                ('gpu_sprites', sprites, 'uint8_t'),
                                ('gpu_palette', palette, 'uint32_t')]:
        f.write(f'static const {ctype} {name}[{len(values)}] = {{\n')
        for off in range(0, len(values), 16):
            f.write('    ' + ','.join(hex(v) for v in values[off:off+16]) + ',\n')
        f.write('};\n')
print('Generated tiles, sprites, tilemap, palette and C header in', OUT)
